"""Build the single-file competition agent from the engine package.

    python scripts/build_submission.py            # writes build/agent.py
    python scripts/build_submission.py out.py     # or a path of your choice

The AI Chessathon platform imports one file, `agent.py`, and ships nothing
else, so the six modules in engine/ are concatenated in dependency order and
the two weight files are embedded as text (zlib, then base64). The engine
code itself is copied line for line; the only lines that differ from the
package are the imports and the two that read the weights.

Layout of the output, which mirrors the file that was originally submitted:

    imports
    config, board, hce, nnue, search, agent   (code only)
    embedded weights
    weight loading, then warm-up              (must come last, in this order:
                                               Numba reads a global array when
                                               it compiles the function using it)

tests/test_build.py builds the file and checks it against the same reference
results as the package.
"""
from __future__ import annotations

import base64
import re
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ENGINE = ROOT / "engine"
MODULES = ("config", "board", "hce", "nnue", "search", "agent")

HEADER = '''"""Single-file build of the chess engine. Generated by
scripts/build_submission.py from the modules in engine/ -- edit those, not
this file.

Public API:
    get_move(fen: str, time_left_ms: int) -> str
"""
from __future__ import annotations

import math
import time

import chess
import numpy as np
from numba import njit, objmode
'''

# Lines that exist only because the code is split into modules.
DROP = re.compile(
    r"^(from __future__ import annotations"
    r"|import (math|time|chess|numpy as np)"
    r"|from numba import .*"
    r"|from pathlib import Path"
    r"|from \.\w+ import \*.*"
    r"|_WEIGHTS = .*)$"
)

# Module-level blocks that must run after the weights are defined.
LOAD_V1 = '''try:
    _load_nnue()
except Exception as _nnue_error:  # pragma: no cover - defensive only
    print(f"NNUE LOAD FAILED, falling back to the v7 evaluation: {_nnue_error!r}")
'''
LOAD_V2 = '''if USE_NNUE_V2:
    try:
        _load_nnue2()
    except Exception as _nn2_error:  # pragma: no cover - defensive only
        print(f"NNUE V2 LOAD FAILED, falling back to the v8 network: {_nn2_error!r}")
'''
WARMUP = '''# Warm-up runs last: the weights have to be in place before the kernels
# compile, because numba resolves a global array when it compiles the
# function that reads it.
try:
    warmup()
except Exception as exc:  # pragma: no cover
    # Never swallowed: if compilation fails the validation log has to say so.
    print(f"WARMUP FAILED: {exc!r}")
'''
READS = {
    'raw = (_WEIGHTS / "nnue_v1.bin").read_bytes()': "raw = zlib.decompress(base64.b64decode(_NNUE_BLOB))",
    'raw = (_WEIGHTS / "nnue_v3.bin").read_bytes()': "raw = zlib.decompress(base64.b64decode(_NNUE2_BLOB))",
}


def take(text: str, block: str, where: str) -> str:
    """Remove `block` from `text`; it must occur exactly once."""
    if text.count(block) != 1:
        raise SystemExit(f"build: expected exactly one copy of this block in {where}:\n{block}")
    return text.replace(block, "")


def module_body(name: str) -> str:
    text = (ENGINE / f"{name}.py").read_text(encoding="utf-8").replace("\r\n", "\n")
    if not text.startswith('"""'):
        raise SystemExit(f"build: engine/{name}.py must start with a docstring")
    text = text[text.index('"""', 3) + 3:]
    kept = [line for line in text.split("\n") if not DROP.match(line)]
    for line in kept:
        if re.match(r"^(import|from)\s", line):
            raise SystemExit(f"build: unexpected import in engine/{name}.py: {line}")
    return "\n".join(kept).strip("\n") + "\n"


def blob(path: Path) -> str:
    return base64.b64encode(zlib.compress(path.read_bytes(), 9)).decode("ascii")


def build() -> str:
    body = {name: module_body(name) for name in MODULES}
    body["nnue"] = take(take(body["nnue"], LOAD_V1, "engine/nnue.py"), LOAD_V2, "engine/nnue.py")
    body["agent"] = take(body["agent"], WARMUP, "engine/agent.py")
    for old, new in READS.items():
        if body["nnue"].count(old) != 1:
            raise SystemExit(f"build: expected exactly one weight read in engine/nnue.py: {old}")
        body["nnue"] = body["nnue"].replace(old, "import base64\n    " + new)

    parts = [HEADER]
    for name in MODULES:
        bar = "# " + "=" * 74
        parts.append(f"\n\n{bar}\n# engine/{name}.py\n{bar}\n{body[name].strip(chr(10))}\n")
    parts.append(
        "\n\n# The learned evaluation weights. Data, not code: int16 network\n"
        "# parameters, zlib then base64. Defined here, after every function that\n"
        "# uses them, so the readable part of the file stays readable.\n"
        f'_NNUE_BLOB = "{blob(ENGINE / "weights" / "nnue_v1.bin")}"\n'
        f'_NNUE2_BLOB = "{blob(ENGINE / "weights" / "nnue_v3.bin")}"\n\n'
        + LOAD_V1 + "\n" + LOAD_V2 + "\n" + WARMUP
    )
    return "".join(parts)


def main() -> None:
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "build" / "agent.py"
    out.parent.mkdir(parents=True, exist_ok=True)
    text = build()
    compile(text, str(out), "exec")          # fail here, not on the platform
    out.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {out}  ({out.stat().st_size:,} bytes, {text.count(chr(10)):,} lines)")


if __name__ == "__main__":
    main()
